"""Turn a pip installation report into requirements.lock: every package pinned, with hashes.

    pip install --dry-run --ignore-installed --uploaded-prior-to P7D \
        --report report.json -r requirements.txt
    python scripts/lock_requirements.py report.json > requirements.lock

pip resolves the full dependency tree (transitive packages included) using only
releases uploaded at least 7 days ago. This script checks that age again against
PyPI, independently of pip, and writes the SHA-256 of every file of each pinned
release, so `pip install --require-hashes` works on any platform (amd64 and arm64).
"""

from __future__ import annotations

import json
import sys
import urllib.request
from datetime import datetime, timedelta, timezone

MIN_AGE = timedelta(days=7)


def pypi_release(name: str, version: str) -> list[dict]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        return json.load(response)["urls"]


def main(argv: list[str]) -> int:
    report = json.loads(open(argv[1], encoding="utf-8").read())
    now = datetime.now(timezone.utc)
    lines, too_new = [], []
    for item in sorted(report["install"], key=lambda i: i["metadata"]["name"].lower()):
        name, version = item["metadata"]["name"].lower(), item["metadata"]["version"]
        files = [f for f in pypi_release(name, version) if not f.get("yanked")]
        uploaded = min(datetime.fromisoformat(f["upload_time_iso_8601"].replace("Z", "+00:00")) for f in files)
        if now - uploaded < MIN_AGE:
            too_new.append(f"{name}=={version} (uploaded {uploaded:%Y-%m-%d})")
        hashes = sorted({f["digests"]["sha256"] for f in files})
        lines.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
        print(f"{name}=={version}: uploaded {uploaded:%Y-%m-%d}, {len(hashes)} files", file=sys.stderr)
    if too_new:
        print("newer than 7 days: " + ", ".join(too_new), file=sys.stderr)
        return 1
    print(f"# Generated by scripts/lock_requirements.py on {now:%Y-%m-%d} from requirements.txt; don't edit by hand.")
    print("# Every release is at least 7 days old; install with: pip install --require-hashes -r requirements.lock")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
